package chromeext

import (
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"runtime"
	"strings"
)

// Paths for the installed bridge under the agent data dir.
const (
	relChromeDir     = "chrome"
	relExtensionDir  = "chrome/extension"
	relHostWrapper   = "chrome/chrome-native-host"
	relHostManifest  = "chrome/com.freepeak.xdev_browser.json"
	hostManifestName = "com.freepeak.xdev_browser.json"
)

// Hooks for tests: production points at the OS-specific implementations.
var (
	registerNativeHostFn   = registerNativeHost
	unregisterNativeHostFn = unregisterNativeHost
	nativeManifestPathFn   = nativeManifestPath
)

// InstallOptions configures Install.
type InstallOptions struct {
	// DataDir is ~/.xdev/agent (or override). Required.
	DataDir string
	// XdevBin is the absolute path of the xdev binary the wrapper execs.
	XdevBin string
	// ExtensionSource is the unpacked extension directory to copy. Empty
	// means "use the copy already under DataDir/chrome/extension" (re-install
	// host only).
	ExtensionSource string
	// Listen is written into docs/status only; the host always uses DefaultListen
	// unless XDEV_CHROME_LISTEN is set at runtime.
	Listen string
}

// InstallResult is what Install reports to the CLI.
type InstallResult struct {
	ExtensionDir   string
	HostWrapper    string
	HostManifest   string
	NativeManifest string // path Chrome reads
	ExtensionID    string
	Listen         string
	Browsers       []string
}

// Install copies the extension, writes the native-host wrapper + manifest, and
// registers the manifest for Chrome (and Edge on macOS when present).
func Install(opts InstallOptions) (InstallResult, error) {
	if strings.TrimSpace(opts.DataDir) == "" {
		return InstallResult{}, fmt.Errorf("chromeext: DataDir is required")
	}
	if strings.TrimSpace(opts.XdevBin) == "" {
		return InstallResult{}, fmt.Errorf("chromeext: XdevBin is required")
	}
	listen := opts.Listen
	if listen == "" {
		listen = DefaultListen
	}
	extDir := filepath.Join(opts.DataDir, relExtensionDir)
	if src := strings.TrimSpace(opts.ExtensionSource); src != "" {
		if err := copyDir(src, extDir); err != nil {
			return InstallResult{}, err
		}
	} else if _, err := os.Stat(filepath.Join(extDir, "manifest.json")); err != nil {
		return InstallResult{}, fmt.Errorf("chromeext: no extension at %s (pass ExtensionSource on first install)", extDir)
	}

	wrapper := filepath.Join(opts.DataDir, relHostWrapper)
	if err := writeHostWrapper(wrapper, opts.XdevBin); err != nil {
		return InstallResult{}, err
	}
	hostMan := filepath.Join(opts.DataDir, relHostManifest)
	if err := writeHostManifest(hostMan, wrapper); err != nil {
		return InstallResult{}, err
	}
	browsers, nmPath, err := registerNativeHostFn(hostMan)
	if err != nil {
		return InstallResult{}, err
	}
	return InstallResult{
		ExtensionDir:   extDir,
		HostWrapper:    wrapper,
		HostManifest:   hostMan,
		NativeManifest: nmPath,
		ExtensionID:    ExtensionID,
		Listen:         listen,
		Browsers:       browsers,
	}, nil
}

// Uninstall removes the native-messaging registration and the data-dir chrome
// tree. The loaded unpacked extension in Chrome must be removed by the user.
func Uninstall(dataDir string) error {
	_ = unregisterNativeHostFn()
	return os.RemoveAll(filepath.Join(dataDir, relChromeDir))
}

func writeHostWrapper(path, xdevBin string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	var body string
	if runtime.GOOS == "windows" {
		body = "@echo off\r\n" + quoteWin(xdevBin) + " --chrome-native-host\r\n"
	} else {
		body = "#!/bin/sh\n# Generated by xdev chrome install — do not edit\nexec " + shellQuote(xdevBin) + " --chrome-native-host\n"
	}
	return os.WriteFile(path, []byte(body), 0o755)
}

func writeHostManifest(path, wrapper string) error {
	man := map[string]any{
		"name":        NativeHostName,
		"description": "xdev Browser native host",
		"path":        wrapper,
		"type":        "stdio",
		"allowed_origins": []string{
			"chrome-extension://" + ExtensionID + "/",
		},
	}
	raw, err := json.MarshalIndent(man, "", "  ")
	if err != nil {
		return err
	}
	raw = append(raw, '\n')
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, raw, 0o644)
}

func shellQuote(s string) string {
	if s == "" {
		return "''"
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func quoteWin(s string) string {
	return `"` + strings.ReplaceAll(s, `"`, `""`) + `"`
}

func copyDir(src, dst string) error {
	return filepath.Walk(src, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		if rel == "." {
			return os.MkdirAll(dst, 0o755)
		}
		base := filepath.Base(path)
		if strings.HasSuffix(base, ".pem") || base == "key.pem" || base == "private.pem" {
			return nil
		}
		target := filepath.Join(dst, rel)
		if info.IsDir() {
			return os.MkdirAll(target, 0o755)
		}
		return copyFile(path, target, info.Mode())
	})
}

func copyFile(src, dst string, mode os.FileMode) error {
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return err
	}
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	out, err := os.OpenFile(dst, os.O_CREATE|os.O_TRUNC|os.O_WRONLY, mode.Perm())
	if err != nil {
		return err
	}
	defer out.Close()
	if _, err := io.Copy(out, in); err != nil {
		return err
	}
	return out.Close()
}

// Status reports whether the host manifest and extension dir look installed.
type Status struct {
	ExtensionDir   string `json:"extensionDir"`
	ExtensionOK    bool   `json:"extensionOk"`
	HostWrapper    string `json:"hostWrapper"`
	HostWrapperOK  bool   `json:"hostWrapperOk"`
	NativeManifest string `json:"nativeManifest"`
	NativeOK       bool   `json:"nativeOk"`
	ExtensionID    string `json:"extensionId"`
	Listen         string `json:"listen"`
	NativeHostName string `json:"nativeHostName"`
}

// Probe returns install status under dataDir without starting anything.
func Probe(dataDir string) Status {
	st := Status{
		ExtensionDir:   filepath.Join(dataDir, relExtensionDir),
		HostWrapper:    filepath.Join(dataDir, relHostWrapper),
		ExtensionID:    ExtensionID,
		Listen:         DefaultListen,
		NativeHostName: NativeHostName,
	}
	if _, err := os.Stat(filepath.Join(st.ExtensionDir, "manifest.json")); err == nil {
		st.ExtensionOK = true
	}
	if _, err := os.Stat(st.HostWrapper); err == nil {
		st.HostWrapperOK = true
	}
	st.NativeManifest = nativeManifestPathFn()
	if st.NativeManifest != "" {
		if _, err := os.Stat(st.NativeManifest); err == nil {
			st.NativeOK = true
		}
	}
	return st
}
